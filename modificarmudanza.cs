   public class modificarmudanza : GXProcedure
   {
      public modificarmudanza( )
      {
         context = new GxContext(  );
         DataStoreUtil.LoadDataStores( context);
         dsDataStore1 = context.GetDataStore("DataStore1");
         dsDefault = context.GetDataStore("Default");
         IsMain = true;
      }

      public modificarmudanza( IGxContext context )
      {
         this.context = context;
         IsMain = false;
         dsDataStore1 = context.GetDataStore("DataStore1");
         dsDefault = context.GetDataStore("Default");
      }

      public void execute( SdtMudanza aP0_Mudanza )
      {
         this.AV2Mudanza = aP0_Mudanza;
         initialize();
         ExecutePrivate();
      }

      public void executeSubmit( SdtMudanza aP0_Mudanza )
      {
         this.AV2Mudanza = aP0_Mudanza;
         SubmitImpl();
      }

      protected override void ExecutePrivate( )
      {
         /* GeneXus formulas */
         /* Output device settings */
         args = new Object[] {(SdtMudanza)AV2Mudanza} ;
         ClassLoader.Execute("amodificarmudanza","GeneXus.Programs","amodificarmudanza", new Object[] {context }, "execute", args);
         if ( ( args != null ) && ( args.Length == 1 ) )
         {
         }
         cleanup();
      }

      public override void cleanup( )
      {
         CloseCursors();
         if ( IsMain )
         {
            context.CloseConnections();
         }
      }

      public override void initialize( )
      {
         /* GeneXus formulas. */
      }

      private IGxDataStore dsDataStore1 ;
      private IGxDataStore dsDefault ;
      private SdtMudanza AV2Mudanza ;
      private Object[] args ;
